#!/usr/bin/env bash
# Generates the TypeScript types and the Pydantic models from contracts/*.schema.json.
#   ./scripts/contracts.sh          writes worker/src/contracts/ and node/src/yt_digest_node/contracts/
#   ./scripts/contracts.sh --check  regenerates into a temporary directory, exits 1 naming the stale files
# Installs its own dependencies (npm ci, uv sync), so it runs on a fresh checkout.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

ts_rel=worker/src/contracts
py_rel=node/src/yt_digest_node/contracts

mode="write"
case "${1:-}" in
  "") ;;
  --check) mode="check" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

(cd worker && npm ci --silent)
(cd node && uv sync --locked --quiet)

# Replaces each {"$ref": "<other>.schema.json"} by the generated type of <other> (no second definition) and
# writes the TypeScript imports it needs to the file given as third argument.
resolve_refs() {
  # shellcheck disable=SC2016  # the JavaScript is meant to be literal
  node -e '
    const fs = require("fs"), path = require("path");
    const [file, dir, imports] = process.argv.slice(1);
    const used = [];
    const walk = (v) => {
      if (Array.isArray(v)) return v.map(walk);
      if (v === null || typeof v !== "object") return v;
      if (typeof v.$ref === "string" && v.$ref.endsWith(".schema.json")) {
        const name = path.basename(v.$ref, ".schema.json");
        const title = JSON.parse(fs.readFileSync(path.join(dir, v.$ref), "utf8")).title;
        used.push(`import type { ${title} } from "./${name}";`);
        return { tsType: title, customTypePath: `yt_digest_node.contracts.${name.replaceAll("-", "_")}.${title}` };
      }
      return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x)]));
    };
    const schema = walk(JSON.parse(fs.readFileSync(file, "utf8")));
    process.stdout.write(JSON.stringify(schema));
    fs.writeFileSync(imports, used.join("\n") + (used.length ? "\n" : ""));
  ' "$@"
}

generate() {
  local out="$1" schema name snake work
  work="$(mktemp -d)"
  mkdir -p "$out/$ts_rel" "$out/$py_rel"
  printf '# Generated by scripts/contracts.sh from contracts/*.schema.json. Do not edit.\n' >"$out/$py_rel/__init__.py"
  for schema in contracts/*.schema.json; do
    name="$(basename "$schema" .schema.json)"
    snake="${name//-/_}"
    # The resolved schema keeps the file name, which datamodel-codegen writes in its header.
    resolve_refs "$schema" contracts "$work/imports" >"$work/$name.schema.json"
    {
      printf '// Generated by scripts/contracts.sh from %s. Do not edit.\n' "$schema"
      cat "$work/imports"
      worker/node_modules/.bin/json2ts --input "$work/$name.schema.json" --bannerComment ""
    } >"$out/$ts_rel/$name.ts"
    {
      printf '# Generated by scripts/contracts.sh from %s. Do not edit.\n' "$schema"
      (cd node && uv run --locked --quiet datamodel-codegen --input "$work/$name.schema.json" \
        --input-file-type jsonschema --output-model-type pydantic_v2.BaseModel \
        --target-python-version 3.12 --use-standard-collections --use-union-operator \
        --use-specialized-enum --use-annotated --field-constraints --disable-timestamp --formatters ruff-check ruff-format)
    } >"$out/$py_rel/$snake.py"
  done
  rm -rf "$work"
}

if [[ "$mode" == write ]]; then
  generate "$root"
  exit 0
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
generate "$tmp"
stale=0
for rel in "$ts_rel" "$py_rel"; do
  # Compare both ways so that a missing or an extra generated file is named too.
  while IFS= read -r f; do
    if ! cmp -s "$root/$f" "$tmp/$f"; then
      echo "stale generated file: $f" >&2
      stale=1
    fi
  done < <(cd "$tmp" && find "$rel" -type f \( -name "*.py" -o -name "*.ts" \) | sort; cd "$root" && find "$rel" -type f \( -name "*.py" -o -name "*.ts" \) 2>/dev/null | sort) 
done
if [[ "$stale" == 1 ]]; then
  echo "run ./scripts/contracts.sh to regenerate" >&2
  exit 1
fi
