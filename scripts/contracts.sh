#!/usr/bin/env bash
# Generates the TypeScript types and Pydantic models from contracts/*.schema.json.
# With --check, regenerates into a temporary directory and exits 1 naming stale files.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

mode="${1:-}"
if [[ -n "$mode" && "$mode" != "--check" ]]; then
  echo "usage: $0 [--check]" >&2
  exit 2
fi

header="GENERATED by scripts/contracts.sh from contracts/*.schema.json. DO NOT EDIT."

# generate <out-root>: writes <out-root>/ts and <out-root>/py
generate() {
  local out="$1" schema name
  mkdir -p "$out/ts" "$out/py"
  for schema in contracts/*.schema.json; do
    name="$(basename "$schema" .schema.json)"
    (
      cd worker
      npx json2ts --input "$root/$schema" --output "$out/ts/$name.ts" \
        --bannerComment "/* $header */" --no-additionalProperties >/dev/null
    )
    (
      cd node
      uv run --quiet datamodel-codegen --input "$root/$schema" --input-file-type jsonschema \
        --output "$out/py/${name//-/_}.py" --output-model-type pydantic_v2.BaseModel \
        --target-python-version 3.12 --use-specialized-enum --use-title-as-name \
        --disable-timestamp --field-constraints --no-use-specialized-enum \
        --formatters ruff-check ruff-format >/dev/null
      # Enums are generated as enum.StrEnum.
      sed -i -e 's/^class \(.*\)(Enum):/class \1(StrEnum):/' -e 's/^from enum import Enum$/from enum import StrEnum/' \
        "$out/py/${name//-/_}.py"
      sed -i "1i # $header" "$out/py/${name//-/_}.py"
    )
  done
  # The catalogue as a runtime list and a TypeScript union type.
  node -e '
    const s = JSON.parse(require("fs").readFileSync(process.argv[1], "utf8"));
    const names = s.properties.event.enum.map((e) => JSON.stringify(e));
    console.log("/* " + process.argv[2] + " */\n");
    console.log("export const LOG_EVENTS = [" + names.join(", ") + "] as const;\n");
    console.log("export type LogEventName = (typeof LOG_EVENTS)[number];");
  ' contracts/log-event.schema.json "$header" >"$out/ts/log-events.ts"
}

sync_from() {
  local out="$1"
  rm -rf worker/src/contracts node/src/yt_digest_node/contracts
  mkdir -p worker/src/contracts node/src/yt_digest_node/contracts
  cp "$out"/ts/*.ts worker/src/contracts/
  cp "$out"/py/*.py node/src/yt_digest_node/contracts/
  printf '# %s\n' "$header" >node/src/yt_digest_node/contracts/__init__.py
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [[ -z "$mode" ]]; then
  generate "$tmp/out"
  sync_from "$tmp/out"
  exit 0
fi

generate "$tmp/out"
mkdir -p "$tmp/expected"
(
  cd "$tmp/expected"
  mkdir -p worker/src/contracts node/src/yt_digest_node/contracts
  cp "$tmp"/out/ts/*.ts worker/src/contracts/
  cp "$tmp"/out/py/*.py node/src/yt_digest_node/contracts/
  printf '# %s\n' "$header" >node/src/yt_digest_node/contracts/__init__.py
)
stale=()
while IFS= read -r f; do
  if [[ ! -f "$root/$f" ]] || ! cmp -s "$tmp/expected/$f" "$root/$f"; then
    stale+=("$f")
  fi
done < <(cd "$tmp/expected" && find worker node -type f | sort)
while IFS= read -r f; do
  [[ -f "$tmp/expected/$f" ]] || stale+=("$f")
done < <(
  cd "$root"
  { find worker/src/contracts node/src/yt_digest_node/contracts -type f -not -name '*.pyc' 2>/dev/null || true; } | sort
)
if ((${#stale[@]} > 0)); then
  echo "generated files are stale (run ./scripts/contracts.sh):" >&2
  printf '  %s\n' "${stale[@]}" >&2
  exit 1
fi
echo "contracts up to date"
